USE WAREHOUSE SNOWFLAKE_LEARNING_WH;
USE DATABASE GLOBAL_TRADE_DB;

-- 1. Check missing values across Gold columns
SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(QUARTER_CODE IS NULL) AS NULL_QUARTER_CODE,
    COUNT_IF(QUARTER IS NULL) AS NULL_QUARTER,
    COUNT_IF(LOCATION_CODE IS NULL) AS NULL_LOCATION_CODE,
    COUNT_IF(LOCATION IS NULL) AS NULL_LOCATION,
    COUNT_IF(PROPERTY_TYPE_CODE IS NULL) AS NULL_PROPERTY_TYPE_CODE,
    COUNT_IF(PROPERTY_TYPE IS NULL) AS NULL_PROPERTY_TYPE,
    COUNT_IF(BEDROOM_CODE IS NULL) AS NULL_BEDROOM_CODE,
    COUNT_IF(BEDROOM IS NULL) AS NULL_BEDROOM,

    COUNT_IF(RENT_VALUE IS NULL) AS NULL_RENT_VALUE,
    COUNT_IF(PREVIOUS_YEAR_RENT IS NULL) AS NULL_PREVIOUS_YEAR_RENT,
    COUNT_IF(YOY_CHANGE_EUR IS NULL) AS NULL_YOY_CHANGE_EUR,
    COUNT_IF(YOY_CHANGE_PCT IS NULL) AS NULL_YOY_CHANGE_PCT,
    COUNT_IF(VALID_OBSERVATIONS IS NULL) AS NULL_VALID_OBSERVATIONS

FROM GOLD.RENT_ANALYTICS;

-- 2. Check invalid numerical values
SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(RENT_VALUE <= 0) AS NON_POSITIVE_RENT,
    COUNT_IF(PREVIOUS_YEAR_RENT <= 0) AS NON_POSITIVE_PREVIOUS_RENT,

    COUNT_IF(
        YOY_CHANGE_EUR IS NOT NULL
        AND RENT_VALUE IS NOT NULL
        AND PREVIOUS_YEAR_RENT IS NOT NULL
        AND ABS(
            YOY_CHANGE_EUR - (RENT_VALUE - PREVIOUS_YEAR_RENT)
        ) > 0.01
    ) AS INCONSISTENT_YOY_EUR,

    COUNT_IF(
        YOY_CHANGE_PCT IS NOT NULL
        AND RENT_VALUE IS NOT NULL
        AND PREVIOUS_YEAR_RENT IS NOT NULL
        AND ABS(
            YOY_CHANGE_PCT -
            ((RENT_VALUE - PREVIOUS_YEAR_RENT)
            / PREVIOUS_YEAR_RENT * 100)
        ) > 0.01
    ) AS INCONSISTENT_YOY_PCT

FROM GOLD.RENT_ANALYTICS;

-- 3. Check duplicate analytical records
SELECT
    COUNT(*) AS DUPLICATE_KEY_GROUPS,
    COALESCE(SUM(RECORD_COUNT - 1), 0) AS EXCESS_DUPLICATE_RECORDS
FROM (
    SELECT
        QUARTER_CODE,
        LOCATION_CODE,
        PROPERTY_TYPE_CODE,
        BEDROOM_CODE,
        COUNT(*) AS RECORD_COUNT
    FROM GOLD.RENT_ANALYTICS
    GROUP BY
        QUARTER_CODE,
        LOCATION_CODE,
        PROPERTY_TYPE_CODE,
        BEDROOM_CODE
    HAVING COUNT(*) > 1
);

-- 4. Validate quarter codes and labels
SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(
        NOT REGEXP_LIKE(QUARTER_CODE, '^[0-9]{4}[1-4]$')
    ) AS INVALID_QUARTER_CODES,

    COUNT(DISTINCT QUARTER_CODE) AS DISTINCT_QUARTERS,

    MIN(QUARTER) AS FIRST_QUARTER_LABEL,
    MAX(QUARTER) AS LAST_QUARTER_LABEL,

    COUNT_IF(
        QUARTER <> LEFT(QUARTER_CODE, 4)
        || 'Q' || RIGHT(QUARTER_CODE, 1)
    ) AS QUARTER_LABEL_MISMATCHES

FROM GOLD.RENT_ANALYTICS;

-- 5. Validate observation availability flag
SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(
        VALID_OBSERVATIONS = 1
        AND RENT_VALUE IS NULL
    ) AS VALID_FLAG_WITHOUT_RENT,

    COUNT_IF(
        VALID_OBSERVATIONS = 0
        AND RENT_VALUE IS NOT NULL
    ) AS INVALID_FLAG_WITH_RENT,

    COUNT_IF(
        VALID_OBSERVATIONS NOT IN (0, 1)
    ) AS INVALID_FLAG_VALUES,

    COUNT_IF(
        (VALID_OBSERVATIONS = 1 AND RENT_VALUE IS NOT NULL)
        OR
        (VALID_OBSERVATIONS = 0 AND RENT_VALUE IS NULL)
    ) AS CONSISTENT_FLAG_RECORDS

FROM GOLD.RENT_ANALYTICS;

-- 6. Validate year-over-year metric availability
SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(
        YOY_CHANGE_EUR IS NOT NULL
        AND (
            RENT_VALUE IS NULL
            OR PREVIOUS_YEAR_RENT IS NULL
        )
    ) AS YOY_WITHOUT_REQUIRED_INPUTS,

    COUNT_IF(
        YOY_CHANGE_PCT IS NOT NULL
        AND (
            RENT_VALUE IS NULL
            OR PREVIOUS_YEAR_RENT IS NULL
        )
    ) AS YOY_PCT_WITHOUT_REQUIRED_INPUTS,

    COUNT_IF(
        RENT_VALUE IS NOT NULL
        AND PREVIOUS_YEAR_RENT IS NOT NULL
        AND (
            YOY_CHANGE_EUR IS NULL
            OR YOY_CHANGE_PCT IS NULL
        )
    ) AS MISSING_YOY_WITH_AVAILABLE_INPUTS,

    COUNT_IF(
        RENT_VALUE IS NULL
        AND PREVIOUS_YEAR_RENT IS NULL
        AND (
            YOY_CHANGE_EUR IS NOT NULL
            OR YOY_CHANGE_PCT IS NOT NULL
        )
    ) AS YOY_WITHOUT_ANY_RENT_INPUT

FROM GOLD.RENT_ANALYTICS;