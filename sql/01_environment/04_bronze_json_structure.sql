
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;
USE DATABASE GLOBAL_TRADE_DB;

SELECT
    TYPEOF(RAW_JSON) AS JSON_TYPE,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(
        COUNT(*) * 100.0 /
        SUM(COUNT(*)) OVER (),
        2
    ) AS PERCENTAGE
FROM BRONZE.RAW_RENT_DATA
GROUP BY TYPEOF(RAW_JSON)
ORDER BY TOTAL_RECORDS DESC;
